#!/usr/bin/env python3
"""Destination map of the whole world as data (offline, no server needed).

Merges  docs/world_graph.json (rooms + door/edge/zone/travel-portal links, from prime_server/scripts/worldgraph.py)
        docs/bot_unreachable_rooms.md (owner's exclusion tables: the reason is kept per room)
        docs/room_reachability_grid.json (server-rule walkable-grid result per room, from roomreach.py)
into  docs/world_map.json  and  docs/world_map.md.

Per room: status, reason, hops from the nearest town portal arrival (walking links only, portal hops counted separately),
one-way links in/out, grid result. Statuses:
  EXCLUDED   owner decision (reason copied from the table)
  OPEN       not excluded and reachable from a town arrival  -> a legal bot destination
  GAP        not excluded and NOT reachable from any town arrival -> needs a look (the list we must explain)
Run from the project root:  python3 claude_tools/worldmap.py
"""
import json, re, collections, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
g = json.load(open(f"{ROOT}/docs/world_graph.json"))
nodes = {n["rid"]: n for n in g["nodes"]}
TOWNS = {50: "Tos", 200: "Marion", 300: "Raza", 350: "Jasper", 101: "Barloque", 150: "Cor Noth", 2000: "Ko'catan",
         2800: "Bergen", 578: "Brax", 38: "Castle Victoria", 4300: "Proving Grounds"}

# owner's exclusion reasons: table rows "| rid | name | level | reason |" in sections 1 and 2 of the unreachable doc
excl = {}
for line in open(f"{ROOT}/docs/bot_unreachable_rooms.md"):
    m = re.match(r"\|\s*(\d+)\s*\|\s*([^|]*)\|\s*([^|]*)\|\s*([^|]*)\|", line)
    if m: excl[int(m.group(1))] = m.group(4).strip()
extra = json.load(open(f"{ROOT}/docs/world_map_exclusions.json"))["rooms"]   # layer 3, provisional, audited later with the owner
for k, v in extra.items():
    if int(k) in nodes and int(k) not in excl: excl[int(k)] = v
for rid, n in nodes.items():              # reasons the graph builder already knew
    if n.get("excluded") and rid not in excl: excl[rid] = n["excluded"]

walk, portal = collections.defaultdict(set), collections.defaultdict(set)
for l in g["links"]:
    (portal if l["type"] == "travel portal" else walk)[l["from"]].add(l["to"])
allout = {r: walk[r] | portal[r] for r in set(walk) | set(portal)}
pairs = {(a, b) for a, bs in allout.items() for b in bs}
oneway_out = collections.defaultdict(list); oneway_in = collections.defaultdict(list)
for a, b in pairs:
    if (b, a) not in pairs: oneway_out[a].append(b); oneway_in[b].append(a)

# hops by WALKING links from any town arrival room (portals are free, so every town room starts at 0)
hops, route = {t: 0 for t in TOWNS}, {t: [t] for t in TOWNS}
q = collections.deque(TOWNS)
while q:
    x = q.popleft()
    for y in walk[x]:
        if y not in hops: hops[y] = hops[x] + 1; route[y] = route[x] + [y]; q.append(y)
# rooms reachable only with one-way help are still reached here (links are directed); mark if the way back is missing
grid = {r["rid"]: r for r in json.load(open(f"{ROOT}/docs/room_reachability_grid.json"))}

def grid_note(rid):
    r = grid.get(rid)
    if not r: return ""
    bad = [e for e in r["ent"] if not e["in_main"]] + [d for d in r["door"] if not d["in_main"]]
    return "grid ok" if not bad else f"grid: {len(bad)} entrance/door outside main region"

out = []
for rid in sorted(nodes):
    n = nodes[rid]
    if rid in excl: st, why = "EXCLUDED", excl[rid]
    elif rid in hops: st, why = "OPEN", ""
    else: st, why = "GAP", "no walking link from any town arrival" + (" (nothing links to it at all)" if not any(rid in allout[a] for a in allout) else "")
    way_back = bool(rid in hops and any(hops.get(b) is not None for b in walk[rid]))
    out.append({"rid": rid, "name": n["name"], "status": st, "reason": why, "hops": hops.get(rid),
                "route": route.get(rid), "one_way_out": sorted(oneway_out[rid]), "one_way_in": sorted(oneway_in[rid]),
                "links_out": sorted(walk[rid]), "grid": grid_note(rid), "town": TOWNS.get(rid)})
json.dump(out, open(f"{ROOT}/docs/world_map.json", "w"), indent=1)

cnt = collections.Counter(o["status"] for o in out)
md = [f"# World map (generated by claude_tools/worldmap.py)\n", f"{len(out)} rooms: {cnt['OPEN']} OPEN (legal bot destinations), {cnt['EXCLUDED']} EXCLUDED (owner), {cnt['GAP']} GAP (not excluded but not reachable).",
      "Hops = walking-link steps (doors, edge exits, zone exits) from the nearest town portal arrival; the 11 portal rooms are hop 0 because portals are free.\n",
      "## GAP rooms (to explain, one by one)\n", "| room | name | why | one-way in | one-way out | links out |", "|---|---|---|---|---|---|"]
for o in out:
    if o["status"] == "GAP": md.append(f"| {o['rid']} | {o['name']} | {o['reason']} | {o['one_way_in']} | {o['one_way_out']} | {o['links_out']} |")
md += ["\n## One-way links (a bot that takes one cannot come back by walking)\n", "| from | to | from name | to name |", "|---|---|---|---|"]
for a, b in sorted(pairs):
    if (b, a) not in pairs and a in nodes and b in nodes: md.append(f"| {a} | {b} | {nodes[a]['name']} | {nodes[b]['name']} |")
md += ["\n## OPEN rooms by distance from a town\n", "| hops | rooms |", "|---|---|"]
by = collections.defaultdict(list)
for o in out:
    if o["status"] == "OPEN": by[o["hops"]].append(f"{o['rid']} {o['name']}")
for h in sorted(by): md.append(f"| {h} | {'; '.join(by[h])} |")
md += ["\n## EXCLUDED rooms (owner)\n", "| room | name | reason |", "|---|---|---|"]
for o in out:
    if o["status"] == "EXCLUDED": md.append(f"| {o['rid']} | {o['name']} | {o['reason']} |")
open(f"{ROOT}/docs/world_map.md", "w").write("\n".join(md) + "\n")
print(dict(cnt)); print("GAP:", [o["rid"] for o in out if o["status"] == "GAP"])
